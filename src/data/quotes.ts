export function getRandomQuote(seed?: number): Quote {
  const i = seed !== undefined ? seed % QUOTES.length : Math.floor(Math.random() * QUOTES.length)
  return QUOTES[i]
}

export function getQuoteText(quote: Quote, lang: string): string {
  return quote.translations[lang] ?? quote.en
}
